type Roles = { t?: string[]; s?: string[]; st?: string[] };

interface VariantSeed {
  id: string;
  exerciseId: string;
  name: string;
  equipmentKind: EquipmentKind;
  config?: Record<string, string>;
  laterality?: Laterality;
  implements?: 1 | 2;
  loadConvention: LoadConvention;
  loadNote?: string;
  measure?: MeasureKind;
  requiresEquipmentInstance?: boolean;
  roles: Roles;
  technique: Omit<TechniqueText, 'authoredBy' | 'reviewStatus' | 'more'> & { more?: TechniqueText['more'] };
}

function variant(s: VariantSeed): ExerciseVariant {
  const muscles: { muscleId: string; role: MuscleRole }[] = [
    ...(s.roles.t ?? []).map((muscleId) => ({ muscleId, role: 'target' as const })),
    ...(s.roles.s ?? []).map((muscleId) => ({ muscleId, role: 'synergist' as const })),
    ...(s.roles.st ?? []).map((muscleId) => ({ muscleId, role: 'stabilizer' as const })),
  ];
  const machineLike = s.equipmentKind === 'machine' || s.equipmentKind === 'cable' || s.equipmentKind === 'smith';
  return {
    id: s.id,
    exerciseId: s.exerciseId,
    name: s.name,
    equipmentKind: s.equipmentKind,
    config: s.config ?? {},
    laterality: s.laterality ?? 'bilateral',
    implements: s.implements ?? 1,
    loadConvention: s.loadConvention,
    ...(s.loadNote ? { loadNote: s.loadNote } : {}),
    measure: s.measure ?? 'reps',
    requiresEquipmentInstance: s.requiresEquipmentInstance ?? machineLike,
    muscles,
    musclesReviewStatus: 'unreviewed',
    technique: { ...s.technique, more: s.technique.more ?? {}, authoredBy: 'atlas', reviewStatus: 'unreviewed' },
    clipId: s.id,
    archived: false,
    custom: false,
    createdAt: SEED_TIME,
    updatedAt: SEED_TIME,
  };
}

